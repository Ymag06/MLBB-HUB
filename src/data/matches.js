// Builds an ISO timestamp relative to today, so sample matches always appear
// around "today". dayOffset: -1 = yesterday, 0 = today, 1 = tomorrow.
function at(dayOffset, hour, minute = 0) {
  const date = new Date();
  date.setDate(date.getDate() + dayOffset);
  date.setHours(hour, minute, 0, 0);
  return date.toISOString();
}

// Shortcut for one game result: game number, winning team id, length in seconds.
function g(number, winnerTeamId, durationSeconds) {
  return { number, winnerTeamId, durationSeconds };
}

